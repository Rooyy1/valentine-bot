def build_product_card(key: str) -> str:
    """Единая функция форматирования карточки продукта: название, цена,
    короткое описание и состав. Используется во всех местах, где нужно
    показать продукт (handlers/product.py, handlers/diagnostics.py),
    чтобы формат и цена никогда не расходились между экранами.
    """
    product = PRODUCTS[key]
    features = "\n".join(product["features"])
    return (
        f"<b>{product['title']}</b>\n"
        f"💰 {product['price']}\n\n"
        f"{product['short']}\n\n"
        f"{features}"
    )
