def build_product_card(key: str, highlight: str | None = None) -> str:
    """Собирает карточку товара. Если highlight задан, подсвечивает фичу,
    в тексте которой встречается эта подстрока (используется для лёгкой
    персонализации по итогам диагностики)."""
    product = PRODUCTS[key]
    feature_lines = []
    for feature in product["features"]:
        if highlight and highlight in feature:
            feature_lines.append(f"<b>{feature}</b> ⭐")
        else:
            feature_lines.append(feature)
    features = "\n".join(feature_lines)
    return f"<b>{product['title']}</b>\n💰 {product['price']}\n\n{product['short']}\n\n{features}"
